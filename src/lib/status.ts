export function statusCodesOf(bird: Bird) {
  return String(bird.status || "")
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);
}

export function statusText(bird: Bird) {
  return statusCodesOf(bird)
    .map((code) => statusLabels[code] || "")
    .filter(Boolean)
    .join(", ");
}

export function taxonParts(bird: Bird) {
  return [bird.familyKa, statusText(bird)].filter((part): part is string => Boolean(part));
}
